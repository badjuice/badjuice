// Writes the profile README and its one image (assets/header.svg, in
// Monkeytype's 9009 colours) from live GitHub data. Run daily by
// .github/workflows/refresh.yml.
//
//   node tools/render.mjs        (set GITHUB_TOKEN to avoid API rate limits)
import { writeFileSync } from 'node:fs';

const LOGIN = 'badjuice';
const NAME = 'Nox Fortes';
// Same text as the portfolio (badjuice.github.io, js/profile.js).
const BIO =
  'I build small tools for problems I keep running into: moving Epic Games installs between drives, ' +
  'bookmarking every open tab at once, turning web pages into PDFs. Lately also a card game you can play ' +
  'in the browser. Mostly C#, PowerShell, JavaScript, TypeScript and Python. I wanted to write something ' +
  'more meaningful here, but I think there is a character lim';
const PINNED = ['tximtxom', 'EpicLibraryToolExplode', 'TabsExplode', 'url2pdf'];

// 9009 theme (monkeytype frontend/src/ts/constants/themes.ts)
const C = { bg: '#eeebe2', main: '#080909', sub: '#99947f', accent: '#7fa480' };

const root = new URL('..', import.meta.url);
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function header() {
  const W = 900;
  const H = 120;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" role="img" aria-label="${NAME} (${LOGIN})">
<title>${NAME} (${LOGIN})</title>
<style>text{font-family:system-ui,-apple-system,'Segoe UI',Roboto,'Helvetica Neue',Arial,sans-serif}</style>
<rect width="${W}" height="${H}" rx="12" fill="${C.bg}"/>
<circle cx="48" cy="60" r="7" fill="${C.accent}"/>
<text x="72" y="58" font-size="30" font-weight="600" fill="${C.main}">${NAME}</text>
<text x="72" y="84" font-size="17" fill="${C.sub}">${LOGIN}</text>
</svg>
`;
}

const headers = { Accept: 'application/vnd.github+json', 'User-Agent': `${LOGIN}-profile-render` };
if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
const r = await fetch(`https://api.github.com/users/${LOGIN}/repos?per_page=100&type=owner`, { headers });
if (!r.ok) throw new Error(`repos: ${r.status}`);
const own = (await r.json()).filter((x) => !x.fork && !x.private);
const pinned = PINNED.map((n) => own.find((x) => x.name === n)).filter(Boolean);

const live = (repo) => repo.homepage || (repo.has_pages ? `https://${LOGIN}.github.io/${repo.name}/` : null);
const project = (repo) => {
  const head = [`**[${repo.name}](${repo.html_url})**`];
  if (repo.language) head.push(repo.language);
  if (live(repo)) head.push(`[${repo.name === 'tximtxom' ? 'play' : 'open'}](${live(repo)})`);
  return repo.description ? `${head.join(' · ')}  \n${repo.description}` : head.join(' · ');
};

writeFileSync(new URL('assets/header.svg', root), header());
writeFileSync(
  new URL('README.md', root),
  `<img src="assets/header.svg" width="900" alt="${NAME} (${LOGIN})">

${BIO}

${pinned.map(project).join('\n\n')}

[${LOGIN}.github.io](https://${LOGIN}.github.io/)

<!-- Generated by tools/render.mjs. Edit that file, not this one. -->
`,
);
console.log(`rendered README with ${pinned.length} projects`);
